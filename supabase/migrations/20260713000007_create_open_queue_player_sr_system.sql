-- Adding an identity to a populated table does not promise application order.
-- Re-sequence the existing append-only ledger by its original stable order,
-- then advance the identity before any migration backfill appends new events.
with ordered_events as (
  select
    event.id,
    row_number() over (order by event.created_at, event.id)::bigint
      as applied_sequence
  from public.player_rating_events event
)
update public.player_rating_events event
set applied_sequence = ordered.applied_sequence
from ordered_events ordered
where event.id = ordered.id;

select setval(
  pg_get_serial_sequence(
    'public.player_rating_events',
    'applied_sequence'
  )::regclass,
  greatest(coalesce(max(event.applied_sequence), 0), 1),
  count(*) > 0
)
from public.player_rating_events event;

