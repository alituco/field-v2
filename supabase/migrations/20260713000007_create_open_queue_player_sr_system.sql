on public.player_rating_events (profile_id, applied_sequence desc);

create or replace function public.calculate_player_sr_change(
  player_rating_to_use integer,
  opponent_average_to_use numeric,
  result_to_use text
)
returns table (
  expected_score numeric,
  actual_score numeric,
  rating_change integer
)
language plpgsql
immutable
set search_path = public
as $$
declare
  raw_change numeric;
  computed_change integer;
begin
  if player_rating_to_use is null or player_rating_to_use < 0 then
    raise exception 'A valid player rating is required.';
  end if;

  if opponent_average_to_use is null or opponent_average_to_use < 0 then
    raise exception 'A valid opponent average is required.';
  end if;

  if result_to_use not in ('WIN', 'LOSS', 'DRAW') then
    raise exception 'A valid player result is required.';
  end if;

  expected_score := 1 / (
    1 + power(
      10::numeric,
      ((opponent_average_to_use - player_rating_to_use)::numeric / 400)
    )
  );
  actual_score := case result_to_use
    when 'WIN' then 1
    when 'LOSS' then 0
    else 0.5
  end;

  raw_change := 24 * (actual_score - expected_score);
  computed_change := round(raw_change)::integer;

  if result_to_use = 'WIN' and computed_change < 3 then
    computed_change := 3;
  elsif result_to_use = 'LOSS' and computed_change > -3 then
    computed_change := -3;
  end if;

  rating_change := greatest(-32, least(32, computed_change));
  return next;
end;
$$;

