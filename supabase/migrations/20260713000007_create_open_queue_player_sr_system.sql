    'profile_id', profile.id,
    'display_name', profile.display_name,
    'username', profile.username,
    'avatar_url', profile.avatar_url,
    'skill_rating', coalesce(rating.skill_rating, 1200),
    'matches_played', coalesce(rating.matches_played, 0),
    'wins', coalesce(rating.wins, 0),
    'losses', coalesce(rating.losses, 0),
    'draws', coalesce(rating.draws, 0),
    'last_change', coalesce(rating.last_change, 0),
    'region', coalesce(rating.region, 'bahrain')
  )
  into summary
  from public.profiles profile
  left join public.player_ratings rating on rating.profile_id = profile.id
  where profile.id = profile_id_to_use;

  if summary is null then
    raise exception 'Player profile not found.';
  end if;

  select coalesce(
    jsonb_agg(event_row.payload order by event_row.applied_sequence desc),
    '[]'::jsonb
  )
  into history
  from (
    select
      event.applied_sequence,
      jsonb_build_object(
        'id', event.id,
        'event_id', event.id,
        'source_type', event.source_type,
        'source_id', event.source_id,
        'played_at', coalesce(
          public.fixture_start_at(fixture.match_date, fixture.time_slot),
          game.starts_at,
          event.effective_at
        ),
        'venue', coalesce(fixture.venue, game.venue),
        'side', event.side,
        'result', event.result,
        'team_name', case
          when event.source_type = 'CLAN_FIXTURE' and event.side = 'HOME'
            then home_clan.name
          when event.source_type = 'CLAN_FIXTURE' and event.side = 'AWAY'
            then away_clan.name
          when event.side = 'WHITE' then 'White Team'
          else 'Black Team'
        end,
        'opponent_name', case
          when event.source_type = 'CLAN_FIXTURE' and event.side = 'HOME'
            then away_clan.name
          when event.source_type = 'CLAN_FIXTURE' and event.side = 'AWAY'
            then home_clan.name
          when event.side = 'WHITE' then 'Black Team'
          else 'White Team'
        end,
        'opponent_label', case
          when event.source_type = 'CLAN_FIXTURE' and event.side = 'HOME'
            then away_clan.name
          when event.source_type = 'CLAN_FIXTURE' and event.side = 'AWAY'
            then home_clan.name
          when event.side = 'WHITE' then 'Black Team'
          else 'White Team'
        end,
        'score_for', case
          when event.source_type = 'CLAN_FIXTURE' and event.side = 'HOME'
            then fixture.home_score
          when event.source_type = 'CLAN_FIXTURE' and event.side = 'AWAY'
            then fixture.away_score
          when event.side = 'WHITE' then game.white_score
          else game.black_score
        end,
        'score_against', case
          when event.source_type = 'CLAN_FIXTURE' and event.side = 'HOME'
            then fixture.away_score
          when event.source_type = 'CLAN_FIXTURE' and event.side = 'AWAY'
            then fixture.home_score
          when event.side = 'WHITE' then game.black_score
          else game.white_score
        end,
        'rating_before', event.rating_before,
        'rating_change', event.rating_change,
        'rating_after', event.rating_after,
        'rating_at_match_start', event.rating_at_match_start,
        'team_average_rating', event.team_average_rating,
        'opponent_average_rating', event.opponent_average_rating,
        'expected_score', event.expected_score,
        'actual_score', event.actual_score,
        'calculation_version', event.calculation_version,
        'applied_sequence', event.applied_sequence,
        'applied_at', event.created_at
      ) as payload
    from public.player_rating_events event
    left join public.fixtures fixture
      on event.source_type = 'CLAN_FIXTURE'
      and fixture.id = event.source_id
    left join public.clans home_clan on home_clan.id = fixture.home_clan_id
    left join public.clans away_clan on away_clan.id = fixture.away_clan_id
    left join public.open_queue_games game
      on event.source_type = 'OPEN_QUEUE'
      and game.id = event.source_id
    where event.profile_id = profile_id_to_use
    order by event.applied_sequence desc
    limit safe_limit
  ) event_row;

  return summary || jsonb_build_object('events', history);
end;
$$;

create or replace function public.season_player_rating_rankings(
  region_to_use text,
  season_starts_on date,
  season_ends_on date
)
returns table (
  rank bigint,
  profile_id uuid,
  display_name text,
  username text,
  avatar_url text,
  skill_rating integer,
  matches_played integer,
  wins integer,
  losses integer,
  draws integer,
  last_change integer,
  region text
)
language sql
stable
security definer
set search_path = public
as $$
  with season_events as (
    select event.*
    from public.player_rating_events event
    join public.player_ratings region_rating
      on region_rating.profile_id = event.profile_id
    where (event.effective_at at time zone 'Asia/Bahrain')::date
      between season_starts_on and season_ends_on
      and lower(region_rating.region) = lower(trim(region_to_use))
  ),
  season_stats as (
    select
      event.profile_id,
      count(*)::integer as matches_played,
      (count(*) filter (where event.result = 'WIN'))::integer as wins,
      (count(*) filter (where event.result = 'LOSS'))::integer as losses,
      (count(*) filter (where event.result = 'DRAW'))::integer as draws
    from season_events event
    group by event.profile_id
    having count(*) >= 2
  ),
  qualified_players as (
    select
      profile.id as profile_id,
      profile.display_name,
      profile.username,
      profile.avatar_url,
      latest_event.rating_after::integer as skill_rating,
      stats.matches_played,
      stats.wins,
      stats.losses,
      stats.draws,
      latest_event.rating_change::integer as last_change,
      rating.region
    from season_stats stats
    join public.player_ratings rating on rating.profile_id = stats.profile_id
    join public.profiles profile on profile.id = stats.profile_id
    join lateral (
      select event.rating_after, event.rating_change
      from season_events event
      where event.profile_id = stats.profile_id
      order by event.applied_sequence desc
      limit 1
    ) latest_event on true
  )
  select
    row_number() over (
      order by
        player.skill_rating desc,
        player.matches_played desc,
        player.wins desc,
        lower(player.display_name),
        player.profile_id
    )::bigint as rank,
    player.profile_id,
    player.display_name,
    player.username,
    player.avatar_url,
    player.skill_rating,
    player.matches_played,
    player.wins,
    player.losses,
    player.draws,
    player.last_change,
    player.region
  from qualified_players player;
$$;

create or replace function public.get_my_season_player_rating(
  region_to_use text,
  season_starts_on date,
  season_ends_on date
)
returns table (
  rank bigint,
  profile_id uuid,
  display_name text,
  username text,
  avatar_url text,
  skill_rating integer,
  matches_played integer,
  wins integer,
  losses integer,
  draws integer,
  last_change integer,
  region text
)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  user_id uuid := auth.uid();
begin
  if user_id is null then
    raise exception 'You need to sign in again.';
  end if;

  if char_length(trim(coalesce(region_to_use, ''))) < 2 then
    raise exception 'Choose a valid leaderboard region.';
  end if;

  if season_starts_on is null
    or season_ends_on is null
    or season_ends_on < season_starts_on
    or season_ends_on - season_starts_on > 370
  then
    raise exception 'Choose a valid leaderboard season.';
  end if;

  return query
  with my_events as (
    select event.*
    from public.player_rating_events event
    where event.profile_id = user_id
      and (event.effective_at at time zone 'Asia/Bahrain')::date
        between season_starts_on and season_ends_on
  ),
  my_stats as (
    select
      count(*)::integer as matches_played,
      (count(*) filter (where event.result = 'WIN'))::integer as wins,
      (count(*) filter (where event.result = 'LOSS'))::integer as losses,
      (count(*) filter (where event.result = 'DRAW'))::integer as draws
    from my_events event
  )
  select
    coalesce(ranking.rank, 0::bigint),
    profile.id,
    profile.display_name,
    profile.username,
    profile.avatar_url,
    coalesce(latest_event.rating_after, rating.skill_rating)::integer,
    stats.matches_played,
    stats.wins,
    stats.losses,
    stats.draws,
    coalesce(latest_event.rating_change, 0)::integer,
    rating.region
  from public.player_ratings rating
  join public.profiles profile on profile.id = rating.profile_id
  cross join my_stats stats
  left join public.season_player_rating_rankings(
    region_to_use,
    season_starts_on,
    season_ends_on
  ) ranking on ranking.profile_id = rating.profile_id
  left join lateral (
    select event.rating_after, event.rating_change
    from my_events event
    order by event.applied_sequence desc
    limit 1
  ) latest_event on true
  where rating.profile_id = user_id
    and lower(rating.region) = lower(trim(region_to_use));
end;
$$;

