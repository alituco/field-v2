create or replace function public.referee_start_open_queue_game(
  game_id_to_start uuid,
  participant_ids_to_use uuid[],
  duration_seconds_to_use integer
)
returns public.open_queue_games
language plpgsql
security definer
set search_path = public
as $$
declare
  game_to_start public.open_queue_games%rowtype;
  started_game public.open_queue_games%rowtype;
  participant_count integer;
  matched_count integer;
  white_count integer;
  black_count integer;
  safe_duration integer;
  kickoff_at timestamptz := clock_timestamp();
begin
  select * into game_to_start
  from public.open_queue_games
  where id = game_id_to_start
  for update;

  if game_to_start.id is null then
    raise exception 'Open Queue game not found.';
  end if;

  if game_to_start.status = 'FINAL' then
    raise exception 'This Open Queue game is already final.';
  end if;

  if game_to_start.status = 'LIVE' then
    raise exception 'This Open Queue game has already started.';
  end if;

  if game_to_start.status <> 'FULL' then
    raise exception 'A solo game must be full before it can be started.';
  end if;

  perform public.assign_open_queue_teams(game_id_to_start);

  if participant_ids_to_use is null
    or cardinality(participant_ids_to_use) = 0
  then
    raise exception 'Confirm the players taking part before starting.';
  end if;

  select
    count(*)::integer,
    count(distinct participant.profile_id)::integer
  into participant_count, matched_count
  from unnest(participant_ids_to_use) participant(profile_id);

  if participant_count <> matched_count
    or exists (
      select 1
      from unnest(participant_ids_to_use) participant(profile_id)
      where participant.profile_id is null
    )
  then
    raise exception 'Each selected player must be listed exactly once.';
  end if;

  select
    count(*)::integer,
    (count(*) filter (where booking.team = 'WHITE'))::integer,
    (count(*) filter (where booking.team = 'BLACK'))::integer
  into matched_count, white_count, black_count
  from public.open_queue_bookings booking
  where booking.game_id = game_id_to_start
    and booking.status = 'CONFIRMED'
    and booking.profile_id = any(participant_ids_to_use);

  if matched_count <> participant_count then
    raise exception 'Every selected player must have a confirmed booking.';
  end if;

  if white_count = 0 or black_count = 0 then
    raise exception 'Select at least one player from each team.';
  end if;

  insert into public.player_ratings (profile_id)
  select participant.profile_id
  from unnest(participant_ids_to_use) participant(profile_id)
  on conflict (profile_id) do nothing;

  perform rating.profile_id
  from public.player_ratings rating
  where rating.profile_id = any(participant_ids_to_use)
  order by rating.profile_id
  for update of rating;

  update public.open_queue_bookings
  set
    played = false,
    rating_at_match_start = null,
    rating_change = null
  where game_id = game_id_to_start
    and status = 'CONFIRMED';

  update public.open_queue_bookings booking
  set
    played = true,
    rating_at_match_start = rating.skill_rating
  from public.player_ratings rating
  where booking.game_id = game_id_to_start
    and booking.status = 'CONFIRMED'
    and booking.profile_id = any(participant_ids_to_use)
    and rating.profile_id = booking.profile_id;

  get diagnostics matched_count = row_count;
  if matched_count <> participant_count then
    raise exception 'Could not save every selected player in the solo lineup.';
  end if;

  safe_duration := greatest(
    600,
    least(7200, coalesce(duration_seconds_to_use, 3600))
  );

  insert into public.open_queue_clock_states (
    game_id,
    status,
    started_at,
    accumulated_seconds,
    duration_seconds
  ) values (
    game_id_to_start,
    'RUNNING',
    kickoff_at,
    0,
    safe_duration
  )
  on conflict (game_id) do update
  set
    status = excluded.status,
    started_at = excluded.started_at,
    accumulated_seconds = excluded.accumulated_seconds,
    duration_seconds = excluded.duration_seconds;

  update public.open_queue_games
  set status = 'LIVE'
  where id = game_id_to_start
  returning * into started_game;

  if not exists (
    select 1
    from public.open_queue_events event
    where event.game_id = game_id_to_start
      and event.event_type = 'MATCH_STARTED'
  ) then
    insert into public.open_queue_events (
      game_id,
      event_type,
      minute,
      second,
      occurred_at
    ) values (
      game_id_to_start,
      'MATCH_STARTED',
      0,
      0,
      kickoff_at
    );
  end if;

  return started_game;
end;
$$;

create or replace function public.referee_start_fixture_atomic(
  fixture_id_to_start uuid,
  participant_ids_to_use uuid[],
  duration_seconds_to_use integer
)
returns public.fixtures
language plpgsql
security definer
set search_path = public
as $$
declare
  fixture_to_start public.fixtures%rowtype;
  started_fixture public.fixtures%rowtype;
  participant_count integer;
  distinct_participant_count integer;
  matched_membership_count integer;
  home_count integer;
  away_count integer;
  saved_count integer;
  safe_duration integer;
  kickoff_at timestamptz := clock_timestamp();
begin
  select * into fixture_to_start
  from public.fixtures
  where id = fixture_id_to_start
  for update;

  if fixture_to_start.id is null then
    raise exception 'Match not found.';
  end if;

  if fixture_to_start.status = 'FINAL' then
    raise exception 'This match is already final.';
  end if;

  if fixture_to_start.status = 'LIVE' then
    raise exception 'This match has already started.';
  end if;

  if fixture_to_start.status <> 'SCHEDULED' then
    raise exception 'Only scheduled matches can be started.';
  end if;

  if fixture_to_start.away_clan_id is null then
    raise exception 'Cannot start a match without an opponent.';
  end if;

  if participant_ids_to_use is null
    or cardinality(participant_ids_to_use) = 0
  then
    raise exception 'Confirm the players taking part before starting.';
  end if;

  select
    count(*)::integer,
    count(distinct participant.profile_id)::integer
  into participant_count, distinct_participant_count
  from unnest(participant_ids_to_use) participant(profile_id);

  if participant_count <> distinct_participant_count
    or exists (
      select 1
      from unnest(participant_ids_to_use) participant(profile_id)
      where participant.profile_id is null
    )
  then
    raise exception 'Each selected player must be listed exactly once.';
  end if;

  select
    count(*)::integer,
    (count(*) filter (
      where member.clan_id = fixture_to_start.home_clan_id
    ))::integer,
    (count(*) filter (
      where member.clan_id = fixture_to_start.away_clan_id
    ))::integer
  into matched_membership_count, home_count, away_count
  from public.clan_members member
  where member.profile_id = any(participant_ids_to_use)
    and member.clan_id in (
      fixture_to_start.home_clan_id,
      fixture_to_start.away_clan_id
    )
    and member.left_at is null;

  if matched_membership_count <> participant_count then
    raise exception 'Every selected player must be an active member of exactly one team in this match.';
  end if;

  if home_count = 0 or away_count = 0 then
    raise exception 'Select at least one player from each team.';
  end if;

  -- Materialize the roster rows while the fixture is still scheduled, then set
  -- the exact played lineup and refresh its match-start SR before LIVE fires the
  -- compatibility snapshot trigger.
  perform public.snapshot_fixture_player_appearances(fixture_id_to_start);

  perform rating.profile_id
  from public.player_ratings rating
  where rating.profile_id = any(participant_ids_to_use)
  order by rating.profile_id
  for update;

  update public.fixture_player_appearances
  set
    played = false,
    rating_change = null
  where fixture_id = fixture_id_to_start;

  update public.fixture_player_appearances appearance
  set
    clan_id = member.clan_id,
    side = case
      when member.clan_id = fixture_to_start.home_clan_id then 'HOME'
      else 'AWAY'
    end,
    played = true,
    rating_at_start = rating.skill_rating,
    rating_change = null
  from public.player_ratings rating,
    public.clan_members member
  where appearance.fixture_id = fixture_id_to_start
    and appearance.profile_id = any(participant_ids_to_use)
    and rating.profile_id = appearance.profile_id
    and member.profile_id = appearance.profile_id
    and member.clan_id in (
      fixture_to_start.home_clan_id,
      fixture_to_start.away_clan_id
    )
    and member.left_at is null;

  get diagnostics saved_count = row_count;
  if saved_count <> participant_count then
    raise exception 'Could not save every selected player in the fixture lineup.';
  end if;

  safe_duration := greatest(
    600,
    least(7200, coalesce(duration_seconds_to_use, 3600))
  );

  insert into public.fixture_clock_states (
    fixture_id,
    status,
    started_at,
    accumulated_seconds,
    duration_seconds
  ) values (
    fixture_id_to_start,
    'RUNNING',
    kickoff_at,
    0,
    safe_duration
  )
  on conflict (fixture_id) do update
  set
    status = excluded.status,
    started_at = excluded.started_at,
    accumulated_seconds = excluded.accumulated_seconds,
    duration_seconds = excluded.duration_seconds;

  update public.fixtures
  set status = 'LIVE'
  where id = fixture_id_to_start
  returning * into started_fixture;

  if not exists (
    select 1
    from public.fixture_events event
    where event.fixture_id = fixture_id_to_start
      and event.event_type = 'MATCH_STARTED'
  ) then
    insert into public.fixture_events (
      fixture_id,
      event_type,
      minute,
      second,
      occurred_at
    ) values (
      fixture_id_to_start,
      'MATCH_STARTED',
      0,
      0,
      kickoff_at
    );
  end if;

  return started_fixture;
end;
$$;

create or replace function public.referee_finish_fixture_atomic(
  fixture_id_to_complete uuid
)
returns public.fixtures
language plpgsql
security definer
set search_path = public
as $$
declare
  fixture_to_finish public.fixtures%rowtype;
  clock_to_stop public.fixture_clock_states%rowtype;
  completed_fixture public.fixtures%rowtype;
  elapsed_seconds integer;
  finish_at timestamptz := clock_timestamp();
begin
  select * into fixture_to_finish
  from public.fixtures
  where id = fixture_id_to_complete
  for update;

  if fixture_to_finish.id is null then
    raise exception 'Match not found.';
  end if;

  if fixture_to_finish.status = 'FINAL' then
    raise exception 'This match is already final.';
  end if;

  if fixture_to_finish.status <> 'LIVE' then
    raise exception 'Only a live match can be finalized.';
  end if;

  select * into clock_to_stop
  from public.fixture_clock_states
  where fixture_id = fixture_id_to_complete
  for update;

  if clock_to_stop.fixture_id is null then
    raise exception 'The match clock has not been started.';
  end if;

  -- Lock both clan rating rows in one deterministic order before the legacy
  -- completion function requests its home/away locks.
  perform clan.id
  from public.clans clan
  where clan.id in (
    fixture_to_finish.home_clan_id,
    fixture_to_finish.away_clan_id
  )
  order by clan.id
  for update;

  elapsed_seconds := least(
    10800,
    greatest(
      0,
      clock_to_stop.accumulated_seconds + case
        when clock_to_stop.status = 'RUNNING'
          and clock_to_stop.started_at is not null
        then greatest(
          0,
          floor(
            extract(epoch from (finish_at - clock_to_stop.started_at))
          )::integer
        )
        else 0
      end
    )
  );

  update public.fixture_clock_states
  set
    status = 'ENDED',
    started_at = null,
    accumulated_seconds = elapsed_seconds
  where fixture_id = fixture_id_to_complete;

  update public.fixture_events
  set
    minute = floor(elapsed_seconds / 60)::integer,
    second = elapsed_seconds % 60,
    occurred_at = finish_at
  where id = (
    select event.id
    from public.fixture_events event
    where event.fixture_id = fixture_id_to_complete
      and event.event_type = 'MATCH_ENDED'
    order by event.occurred_at desc, event.created_at desc, event.id desc
    limit 1
  );

  if not found then
    insert into public.fixture_events (
      fixture_id,
      event_type,
      minute,
      second,
      occurred_at
    ) values (
      fixture_id_to_complete,
      'MATCH_ENDED',
      floor(elapsed_seconds / 60)::integer,
      elapsed_seconds % 60,
      finish_at
    );
  end if;

  select * into completed_fixture
  from public.referee_complete_fixture(fixture_id_to_complete);

  -- referee_complete_fixture supports legacy callers by clamping to the nominal
  -- duration. The atomic wrapper restores the referee's exact stopped time.
  update public.fixture_clock_states
  set
    status = 'ENDED',
    started_at = null,
    accumulated_seconds = elapsed_seconds
  where fixture_id = fixture_id_to_complete;

  return completed_fixture;
end;
$$;

