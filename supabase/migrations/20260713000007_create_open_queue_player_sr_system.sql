create or replace function public.apply_clan_fixture_player_ratings()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  participant record;
  team_average numeric;
  opponent_average numeric;
  expected_score_to_use numeric;
  actual_score_to_use numeric;
  computed_change integer;
  applied_change integer;
  current_rating integer;
  next_rating integer;
  result_to_use text;
  inserted_event uuid;
begin
  if new.status <> 'FINAL' or old.status = 'FINAL' then
    return new;
  end if;

  if new.home_score is null or new.away_score is null then
    return new;
  end if;

  perform public.snapshot_fixture_player_appearances(new.id);

  perform rating.profile_id
  from public.player_ratings rating
  join public.fixture_player_appearances appearance
    on appearance.profile_id = rating.profile_id
  where appearance.fixture_id = new.id
    and appearance.played
  order by rating.profile_id
  for update of rating;

  for participant in
    select appearance.*
    from public.fixture_player_appearances appearance
    where appearance.fixture_id = new.id
      and appearance.played
    order by appearance.profile_id
  loop
    select skill_rating into current_rating
    from public.player_ratings
    where profile_id = participant.profile_id;

    select avg(teammate.rating_at_start)::numeric
    into team_average
    from public.fixture_player_appearances teammate
    where teammate.fixture_id = new.id
      and teammate.played
      and teammate.side = participant.side;

    select avg(opponent.rating_at_start)::numeric
    into opponent_average
    from public.fixture_player_appearances opponent
    where opponent.fixture_id = new.id
      and opponent.played
      and opponent.side <> participant.side;

    if opponent_average is null then
      continue;
    end if;

    if new.home_score = new.away_score then
      result_to_use := 'DRAW';
    elsif
      (participant.side = 'HOME' and new.home_score > new.away_score)
      or (participant.side = 'AWAY' and new.away_score > new.home_score)
    then
      result_to_use := 'WIN';
    else
      result_to_use := 'LOSS';
    end if;

    select
      calculation.expected_score,
      calculation.actual_score,
      calculation.rating_change
    into
      expected_score_to_use,
      actual_score_to_use,
      computed_change
    from public.calculate_player_sr_change(
      participant.rating_at_start,
      opponent_average,
      result_to_use
    ) calculation;

    next_rating := greatest(0, current_rating + computed_change);
    applied_change := next_rating - current_rating;
    inserted_event := null;

    insert into public.player_rating_events (
      profile_id,
      source_type,
      source_id,
      side,
      result,
      rating_before,
      rating_change,
      rating_after,
      effective_at,
      rating_at_match_start,
      team_average_rating,
      opponent_average_rating,
      expected_score,
      actual_score,
      calculation_version
    ) values (
      participant.profile_id,
      'CLAN_FIXTURE',
      new.id,
      participant.side,
      result_to_use,
      current_rating,
      applied_change,
      next_rating,
      public.fixture_start_at(new.match_date, new.time_slot),
      participant.rating_at_start,
      round(team_average, 2),
      round(opponent_average, 2),
      round(expected_score_to_use, 6),
      actual_score_to_use,
      'PLAYER_ELO_V1'
    )
    on conflict (source_type, source_id, profile_id) do nothing
    returning id into inserted_event;

    if inserted_event is not null then
      update public.player_ratings
      set
        skill_rating = next_rating,
        matches_played = matches_played + 1,
        wins = wins + case when result_to_use = 'WIN' then 1 else 0 end,
        losses = losses + case when result_to_use = 'LOSS' then 1 else 0 end,
        draws = draws + case when result_to_use = 'DRAW' then 1 else 0 end,
        last_change = applied_change
      where profile_id = participant.profile_id;

      update public.fixture_player_appearances
      set rating_change = applied_change
      where fixture_id = new.id
        and profile_id = participant.profile_id;
    end if;
  end loop;

  return new;
end;
$$;

create or replace function public.assign_open_queue_teams(
  game_id_to_assign uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  game_to_assign public.open_queue_games%rowtype;
  confirmed_count integer;
  goalkeeper_count integer;
  defender_count integer;
  midfielder_count integer;
  attacker_count integer;
  assignment_is_exact boolean;
  white_booking_ids uuid[];
  white_average numeric;
  black_average numeric;
  overall_average numeric;
begin
  select * into game_to_assign
  from public.open_queue_games
  where id = game_id_to_assign
  for update;

  if game_to_assign.id is null then
    raise exception 'Open Queue game not found.';
  end if;

  if game_to_assign.status <> 'FULL' then
    raise exception 'Teams can only be assigned when an Open Queue game is full.';
  end if;

  select
    count(*)::integer,
    (count(*) filter (where booking.role = 'GK'))::integer,
    (count(*) filter (where booking.role = 'DEF'))::integer,
    (count(*) filter (where booking.role = 'MID'))::integer,
    (count(*) filter (where booking.role = 'ATT'))::integer
  into
    confirmed_count,
    goalkeeper_count,
    defender_count,
    midfielder_count,
    attacker_count
  from public.open_queue_bookings booking
  where booking.game_id = game_id_to_assign
    and booking.status = 'CONFIRMED';

  if confirmed_count <> 12
    or goalkeeper_count <> 2
    or defender_count <> 4
    or midfielder_count <> 4
    or attacker_count <> 2
  then
    raise exception 'A full Open Queue game needs 2 GK, 4 DEF, 4 MID, and 2 ATT players.';
  end if;

  select
    count(*) = 12
    and (count(*) filter (where booking.team = 'WHITE')) = 6
    and (count(*) filter (where booking.team = 'BLACK')) = 6
    and (count(*) filter (
      where booking.team = 'WHITE' and booking.role = 'GK'
    )) = 1
    and (count(*) filter (
      where booking.team = 'WHITE' and booking.role = 'DEF'
    )) = 2
    and (count(*) filter (
      where booking.team = 'WHITE' and booking.role = 'MID'
    )) = 2
    and (count(*) filter (
      where booking.team = 'WHITE' and booking.role = 'ATT'
    )) = 1
    and (count(*) filter (
      where booking.team = 'BLACK' and booking.role = 'GK'
    )) = 1
    and (count(*) filter (
      where booking.team = 'BLACK' and booking.role = 'DEF'
    )) = 2
    and (count(*) filter (
      where booking.team = 'BLACK' and booking.role = 'MID'
    )) = 2
    and (count(*) filter (
      where booking.team = 'BLACK' and booking.role = 'ATT'
    )) = 1
  into assignment_is_exact
  from public.open_queue_bookings booking
  where booking.game_id = game_id_to_assign
    and booking.status = 'CONFIRMED';

  if game_to_assign.teams_assigned_at is not null
    and game_to_assign.white_average_sr is not null
    and game_to_assign.black_average_sr is not null
    and game_to_assign.match_average_sr is not null
    and game_to_assign.team_sr_spread is not null
    and assignment_is_exact
    and not exists (
      select 1
      from public.open_queue_bookings booking
      where booking.game_id = game_id_to_assign
        and booking.status = 'CONFIRMED'
        and (
          booking.team is null
          or booking.rating_at_team_assignment is null
        )
    )
  then
    return;
  end if;

  insert into public.player_ratings (profile_id)
  select booking.profile_id
  from public.open_queue_bookings booking
  where booking.game_id = game_id_to_assign
    and booking.status = 'CONFIRMED'
  on conflict (profile_id) do nothing;

  perform rating.profile_id
  from public.player_ratings rating
  join public.open_queue_bookings booking
    on booking.profile_id = rating.profile_id
  where booking.game_id = game_id_to_assign
    and booking.status = 'CONFIRMED'
  order by rating.profile_id
  for update of rating;

  with participants as (
    select
      booking.id,
      booking.role,
      rating.skill_rating as sr
    from public.open_queue_bookings booking
    join public.player_ratings rating on rating.profile_id = booking.profile_id
    where booking.game_id = game_id_to_assign
      and booking.status = 'CONFIRMED'
  ),
  goalkeeper_choices as (
    select participant.id, participant.sr
    from participants participant
    where participant.role = 'GK'
  ),
  defender_choices as (
    select
      first_player.id as first_id,
      second_player.id as second_id,
      first_player.sr + second_player.sr as sr
    from participants first_player
    join participants second_player
      on first_player.id < second_player.id
    where first_player.role = 'DEF'
      and second_player.role = 'DEF'
  ),
  midfielder_choices as (
    select
      first_player.id as first_id,
      second_player.id as second_id,
      first_player.sr + second_player.sr as sr
    from participants first_player
    join participants second_player
      on first_player.id < second_player.id
    where first_player.role = 'MID'
      and second_player.role = 'MID'
  ),
  attacker_choices as (
    select participant.id, participant.sr
    from participants participant
    where participant.role = 'ATT'
  ),
  total as (
    select sum(participant.sr)::integer as total_sr
    from participants participant
  ),
  candidates as (
    select
      array[
        goalkeeper.id,
        defender.first_id,
        defender.second_id,
        midfielder.first_id,
        midfielder.second_id,
        attacker.id
      ]::uuid[] as booking_ids,
      goalkeeper.sr + defender.sr + midfielder.sr + attacker.sr
        as white_total,
      concat_ws(
        '|',
        goalkeeper.id::text,
        defender.first_id::text,
        defender.second_id::text,
        midfielder.first_id::text,
        midfielder.second_id::text,
        attacker.id::text
      ) as deterministic_key
    from goalkeeper_choices goalkeeper
    cross join defender_choices defender
    cross join midfielder_choices midfielder
    cross join attacker_choices attacker
  )
  select candidate.booking_ids
  into white_booking_ids
  from candidates candidate
  cross join total
  order by
    abs((candidate.white_total * 2) - total.total_sr),
    candidate.deterministic_key
  limit 1;

  if white_booking_ids is null or cardinality(white_booking_ids) <> 6 then
    raise exception 'Could not calculate balanced Open Queue teams.';
  end if;

  update public.open_queue_bookings booking
  set
    team = case
      when booking.id = any(white_booking_ids) then 'WHITE'
      else 'BLACK'
    end,
    rating_at_team_assignment = rating.skill_rating,
    rating_at_match_start = null,
    rating_change = null
  from public.player_ratings rating
  where booking.game_id = game_id_to_assign
    and booking.status = 'CONFIRMED'
    and rating.profile_id = booking.profile_id;

  select
    avg(booking.rating_at_team_assignment) filter (
      where booking.team = 'WHITE'
    ),
    avg(booking.rating_at_team_assignment) filter (
      where booking.team = 'BLACK'
    ),
    avg(booking.rating_at_team_assignment)
  into white_average, black_average, overall_average
  from public.open_queue_bookings booking
  where booking.game_id = game_id_to_assign
    and booking.status = 'CONFIRMED';

  update public.open_queue_games
  set
    white_average_sr = round(white_average, 2),
    black_average_sr = round(black_average, 2),
    match_average_sr = round(overall_average, 2),
    team_sr_spread = round(abs(white_average - black_average), 2),
    teams_assigned_at = clock_timestamp()
  where id = game_id_to_assign;
end;
$$;

create or replace function public.sync_open_queue_game_status()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  game_id_to_sync uuid;
  game_to_sync public.open_queue_games%rowtype;
  confirmed_count integer;
begin
  game_id_to_sync := case when tg_op = 'DELETE' then old.game_id else new.game_id end;

  select * into game_to_sync
  from public.open_queue_games
  where id = game_id_to_sync
  for update;

  if game_to_sync.id is null
    or game_to_sync.status not in ('OPEN', 'FULL')
  then
    return case when tg_op = 'DELETE' then old else new end;
  end if;

  select count(*)::integer into confirmed_count
  from public.open_queue_bookings booking
  where booking.game_id = game_id_to_sync
